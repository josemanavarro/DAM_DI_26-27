    private void jButtonAceptarActionPerformed(java.awt.event.ActionEvent evt) {
        String siglas = this.jTextFieldSiglas.getText().trim();
        String nombre = this.jTextFieldNombre.getText().trim();
        int curso = (Integer) this.jSpinnerCurso.getValue();
        int horas = (Integer) this.jSpinnerHoras.getValue();

        if (siglas.isEmpty() || nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe completar las siglas y el nombre del módulo.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        Modulo modulo = new Modulo(siglas, nombre, curso, horas);

        if (indice == -1) {
            if (jpm != null) {
                jpm.anadirModulo(modulo);
            } else if (jfvp != null) {
                jfvp.anadirModulo(modulo);
            }
        } else {
            if (jpm != null) {
                jpm.editarModulo(modulo, indice);
            } else if (jfvp != null) {
                jfvp.editarModulo(modulo, indice);
            }
        }

        this.dispose();
    }

