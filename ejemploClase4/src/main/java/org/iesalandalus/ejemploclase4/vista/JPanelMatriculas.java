    /**
     * Devuelve el alumno actualmente seleccionado en el ComboBox.
     * 
     * @return Alumno seleccionado o null si no hay ninguno.
     */
    public Alumno getAlumnoSeleccionado() {
        int indice = jComboBox1.getSelectedIndex();
        if (indice >= 0 && lna != null && indice < lna.elementos()) {
            return lna.getAlumnoNumero(indice);
        }
        return null;
    }

    /**
     * Acción del botón para matricular un módulo a un alumno (jButtonMatricularModulo).
     * Abre el diálogo modal JDialogDatosMatricula.
     */
    private void jButtonMatricularModuloActionPerformed(java.awt.event.ActionEvent evt) {
        Alumno alumno = getAlumnoSeleccionado();
        if (alumno == null) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Debe seleccionar un alumno para poder matricularlo.", 
                "Aviso", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        JDialogDatosMatricula dialog = new JDialogDatosMatricula(padre, true, this, alumno);
        dialog.setVisible(true);
    }

    /**
     * Acción del botón para eliminar una matrícula seleccionada (jButtonQuitarMatriculaModulo).
     */
    private void jButtonQuitarMatriculaModuloActionPerformed(java.awt.event.ActionEvent evt) {
        int filaVisual = jTable1.getSelectedRow();
        if (filaVisual == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Debe seleccionar una matrícula de la tabla para eliminar.", 
                "Aviso", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int filaModelo = jTable1.convertRowIndexToModel(filaVisual);
        Matricula matricula = mtm.getMatriculaAt(filaModelo);
        if (matricula == null) {
            return;
        }

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
            "¿Está seguro de que desea eliminar la matrícula del módulo " + matricula.getModuloSiglas() + " (Curso: " + matricula.getCursoAcademico() + ")?", 
            "Confirmar eliminación", 
            javax.swing.JOptionPane.YES_NO_OPTION, 
            javax.swing.JOptionPane.QUESTION_MESSAGE);

        if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
            boolean eliminada = (lnmat != null) && lnmat.eliminarMatricula(matricula);
            if (eliminada) {
                alumnoSeleccionadoCambiado();
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Matrícula eliminada correctamente.", 
                    "Éxito", 
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "No se pudo eliminar la matrícula de la base de datos.", 
                    "Error", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }

    /**
     * Añade una matrícula persistiendo en la base de datos y actualizando la interfaz.
     * 
     * @param matricula Matrícula a registrar.
     * @return true si se insertó con éxito, false en caso contrario.
     */
    public boolean anadirMatricula(Matricula matricula) {
        if (lnmat == null || matricula == null) {
            return false;
        }
        // Validar si el alumno ya está matriculado en ese módulo y curso
        List<Matricula> matriculasActuales = lnmat.getMatriculasPorAlumno(matricula.getAlumnoId());
        if (matriculasActuales != null) {
            for (Matricula m : matriculasActuales) {
                if (m.getModuloSiglas().equalsIgnoreCase(matricula.getModuloSiglas()) &&
                    m.getCursoAcademico().equalsIgnoreCase(matricula.getCursoAcademico())) {
                    javax.swing.JOptionPane.showMessageDialog(this, 
                        "El alumno ya está matriculado en el módulo " + matricula.getModuloSiglas() + " en el curso " + matricula.getCursoAcademico() + ".", 
                        "Matrícula duplicada", 
                        javax.swing.JOptionPane.WARNING_MESSAGE);
                    return false;
                }
            }
        }

        boolean insertada = lnmat.insertarMatricula(matricula);
        if (insertada) {
            alumnoSeleccionadoCambiado();
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Matrícula añadida con éxito.", 
                "Éxito", 
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
            return true;
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "No se pudo guardar la matrícula en la base de datos.", 
                "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
            return false;
        }
    }
