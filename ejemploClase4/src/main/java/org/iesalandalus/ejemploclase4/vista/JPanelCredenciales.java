    private void jButtonAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAceptarActionPerformed
        String login = this.jTextFieldLogin.getText();
        String pass = new String(this.jPasswordInicio.getPassword());
        
        if (login == null || login.trim().isEmpty() || pass.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Por favor, introduzca usuario y contraseña.", 
                "Campos vacíos", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        Credenciales intento = new Credenciales(login.trim(), pass);
        if (credencialesDAO.validar(intento)) {
            this.setVisible(false);
            if (padre != null) {
                padre.loginCorrecto();
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Usuario y contraseña no válidos.", 
                "FALLO", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
            this.jTextFieldLogin.setText("");
            this.jPasswordInicio.setText("");
            this.jTextFieldLogin.requestFocusInWindow();
        }
    }//GEN-LAST:event_jButtonAceptarActionPerformed


