    private void jButtonAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAceptarActionPerformed
        if (alumno == null) {
            JOptionPane.showMessageDialog(this, "No hay ningún alumno seleccionado para matricular.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Object moduloObj = this.jComboBoxModulo.getSelectedItem();
        if (moduloObj == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un módulo.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String textoModulo = moduloObj.toString();
        String moduloSiglas = textoModulo.contains(" - ") ? textoModulo.split(" - ")[0].trim() : textoModulo.trim();
        if (moduloSiglas.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No se pudo determinar la sigla del módulo seleccionado.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String strFecha = this.jTextFieldFecha.getText().trim();
        LocalDate fecha;
        try {
            fecha = LocalDate.parse(strFecha);
        } catch (DateTimeParseException e) {
            JOptionPane.showMessageDialog(this, "La fecha debe tener el formato AAAA-MM-DD (ej: " + LocalDate.now() + ").", "Fecha incorrecta", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String cursoAcademico = this.jTextFieldCurso.getText().trim();
        if (cursoAcademico.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe indicar el curso académico (ej: 25-26).", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        Matricula matricula = new Matricula(alumno.getId(), moduloSiglas, fecha, cursoAcademico);

        if (jpma != null) {
            boolean exito = jpma.anadirMatricula(matricula);
            if (exito) {
                this.dispose();
            }
        } else {
            this.dispose();
        }
    }//GEN-LAST:event_jButtonAceptarActionPerformed

