    public boolean eliminarModulo(int i) {
        if (lnm != null) {
            boolean eliminado = lnm.eliminarModulo(i);
            if (eliminado) {
                actualizarTabla();
                if (padre != null && padre.getJpma() != null) {
                    padre.getJpma().cargarAlumnosComboBox();
                }
            }
            return eliminado;
        }
        return false;
    }

    public void eliminarModuloSeleccionado() {
        int seleccionado = this.jTableModulos.getSelectedRow();
        if (seleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar un módulo para eliminar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int corregido = this.jTableModulos.convertRowIndexToModel(seleccionado);
        Modulo modulo = (lnm != null) ? lnm.getModuloNumero(corregido) : null;
        if (modulo != null) {
            int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
                "¿Está seguro de que desea eliminar el módulo " + modulo.getSiglas() + " - " + modulo.getNombre() + "?\nSe borrarán todas las matrículas de este módulo en cascada.", 
                "Confirmar eliminación", 
                javax.swing.JOptionPane.YES_NO_OPTION, 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
                boolean eliminado = eliminarModulo(corregido);
                if (eliminado) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Módulo y sus matrículas eliminados correctamente.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "No se pudo eliminar el módulo.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        }
    }
