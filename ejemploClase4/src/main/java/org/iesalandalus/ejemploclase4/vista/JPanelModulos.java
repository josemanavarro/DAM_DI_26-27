    private void jButtonModificarActionPerformed(java.awt.event.ActionEvent evt) {                                                 
        int seleccionado = this.jTableModulos.getSelectedRow();
        if (seleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar un módulo para modificar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int corregido = this.jTableModulos.convertRowIndexToModel(seleccionado);
        Modulo modulo = (lnm != null) ? lnm.getModuloNumero(corregido) : null;
        if (modulo != null) {
            JDialogDatosModulos jdd = new JDialogDatosModulos(padre, true, this, modulo, corregido);
            jdd.setVisible(true);
        }
    }                                                

    private void jButtonFiltrarActionPerformed(java.awt.event.ActionEvent evt) {                                               
        String text = jTextFieldFiltrar.getText();
        if (text == null || text.trim().isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + java.util.regex.Pattern.quote(text.trim()), 0, 1));
        }
    }  
    
    public void anadirModulo(Modulo modulo) {
        if (lnm != null) {
            lnm.insertarModulo(modulo);         
            actualizarTabla();
        }
    }
    
    public void editarModulo(Modulo modulo, int i){
        if (lnm != null) {
            lnm.editarModulo(modulo, i);
            actualizarTabla();
        }
    }
    
    private void actualizarTabla(){   
        if (this.mtm != null) {
            this.mtm.fireTableDataChanged();
        } else {
            this.mtm = new ModuloTableModel(lnm);
            this.jTableModulos.setModel(mtm);
            if (sorter != null) {
                sorter.setModel(mtm);
            }
        }
    }

