    public boolean eliminarAlumno(int i) {
        if (lna != null) {
            boolean eliminado = lna.eliminarAlumno(i);
            if (eliminado) {
                actualizarTabla();
                if (padre != null && padre.getJpma() != null) {
                    padre.getJpma().cargarAlumnosComboBox();
                }
            }
            return eliminado;
        }
        return false;
    }

    public void eliminarAlumnoSeleccionado() {
        int seleccionado = this.jTableAlumnos.getSelectedRow();
        if (seleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar un alumno para eliminar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int corregido = this.jTableAlumnos.convertRowIndexToModel(seleccionado);
        Alumno alumno = (lna != null) ? lna.getAlumnoNumero(corregido) : null;
        if (alumno != null) {
            int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this, 
                "¿Está seguro de que desea eliminar al alumno " + alumno.getNombreCompleto() + "?\nSe borrarán todas sus matrículas en cascada.", 
                "Confirmar eliminación", 
                javax.swing.JOptionPane.YES_NO_OPTION, 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
                boolean eliminado = eliminarAlumno(corregido);
                if (eliminado) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Alumno y sus matrículas eliminados correctamente.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "No se pudo eliminar el alumno.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
                }
            }
        }
    }
