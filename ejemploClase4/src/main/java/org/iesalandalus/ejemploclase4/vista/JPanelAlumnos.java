    private void jButtonModificarActionPerformed(java.awt.event.ActionEvent evt) {                                                 
        int seleccionado = this.jTableAlumnos.getSelectedRow();
        if (seleccionado == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debe seleccionar un alumno para modificar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int corregido = this.jTableAlumnos.convertRowIndexToModel(seleccionado);
        Alumno alumno = (lna != null) ? lna.getAlumnoNumero(corregido) : null;
        if (alumno != null) {
            JDialogDatosAlumnos jdd = new JDialogDatosAlumnos(padre, true, alumno, corregido);
            jdd.setVisible(true);
        }
    }                                                

    private void jButtonFiltrarActionPerformed(java.awt.event.ActionEvent evt) {                                               
        String text = jTextFieldFiltrar.getText();
        if (text == null || text.trim().isEmpty()) {
            sorter.setRowFilter(null);
        } else {
            sorter.setRowFilter(RowFilter.regexFilter("(?i)" + java.util.regex.Pattern.quote(text.trim()), 1));
        }
    }  
    
    public void anadirAlumno(Alumno alumno) {
        if (lna != null) {
            lna.insertarAlumno(alumno);         
            actualizarTabla();
        }
    }
    
    public void editarAlumno(Alumno alumno, int i){
        if (lna != null) {
            lna.editarAlumno(alumno, i);
            actualizarTabla();
        }
    }
    
    private void actualizarTabla(){   
        if (this.atm != null) {
            this.atm.fireTableDataChanged();
        } else {
            this.atm = new AlumnoTableModel(lna);
            this.jTableAlumnos.setModel(atm);
            if (sorter != null) {
                sorter.setModel(atm);
            }
        }
    }
    
